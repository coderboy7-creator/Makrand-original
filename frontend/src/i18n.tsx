const dict: Record<Lang, Record<string, string>> = { hi: HI, en: EN };

type Ctx = { lang: Lang; setLang: (l: Lang) => void; t: (k: string) => string };
const C = createContext<Ctx>({ lang: "hi", setLang: () => {}, t: (k) => k });

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    const s = localStorage.getItem("makaranda.lang");
    return s === "en" ? "en" : "hi";
  });
  const setLang = (l: Lang) => {
    localStorage.setItem("makaranda.lang", l);
    setLangState(l);
    document.documentElement.lang = l === "hi" ? "hi" : "en";
  };
  const t = (k: string) => dict[lang][k] || dict.en[k] || k;
  const value = useMemo(() => ({ lang, setLang, t }), [lang]);
  return <C.Provider value={value}>{children}</C.Provider>;
}

export const useI18n = () => useContext(C);
